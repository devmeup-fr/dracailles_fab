/// A Flesh and Blood hero a player can pick to represent them in a match.
///
/// `thumbnailPath`/`photoPath` point under `assets/images/hero_thumbnails/`
/// and `assets/images/hero_photos/` - drop a PNG there named accordingly
/// and it shows up automatically (the whole `assets/images/` tree is
/// already bundled, no pubspec edit needed). Until the file exists, the
/// picker shows a plain placeholder and the match falls back to the
/// player's color.
///
/// Classes and life totals are best-effort and editable here directly.
enum FabHeroClass {
  assassin('Assassin'),
  bard('Bard'),
  brute('Brute'),
  guardian('Guardian'),
  illusionist('Illusionist'),
  mechanologist('Mechanologist'),
  merchant('Merchant'),
  ninja('Ninja'),
  ranger('Ranger'),
  runeblade('Runeblade'),
  thief('Thief'),
  warrior('Warrior'),
  wizard('Wizard'),
  unknown('Unknown');

  final String displayName;
  const FabHeroClass(this.displayName);
}

class FabHero {
  final String name;
  final List<FabHeroClass> heroClasses;
  final String asset;
  final int life;

  const FabHero(this.name, this.heroClasses, this.asset, this.life);

  String get thumbnailPath => 'assets/images/hero_thumbnails/$asset';
  String get photoPath => 'assets/images/hero_photos/$asset';
}

